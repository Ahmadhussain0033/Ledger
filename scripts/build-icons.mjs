// Builds js/icons.js from two open icon libraries, so the page has no runtime
// icon dependency:
//   • Lucide        https://lucide.dev         (ISC)  1,500+ line icons
//   • Simple Icons  https://simpleicons.org    (CC0)  3,000+ brand logos
// To add an icon: put its Lucide name in UI (or its Simple Icons slug in BRANDS)
// and run `node scripts/build-icons.mjs`. Use it in js/app.js as icon("name")
// or icon("brand:slug").
import { writeFile } from "node:fs/promises";

const LUCIDE = "1.57.0";
const SIMPLE = "16.35.0";

// name used in the app → Lucide icon name
const UI = {
  heart: "heart", coffee: "coffee", repeat: "repeat", wallet: "wallet", code: "code", coin: "coins",
  link: "link", arrow: "arrow-up-right", hash: "hash", folder: "folder-git-2", at: "at-sign", sun: "sun-moon",
  copy: "copy", chat: "message-circle", check: "check", up: "thumbs-up", refresh: "refresh-cw", mail: "mail",
  x: "x", dot: "circle-dashed", trophy: "trophy", flag: "flag", users: "users", receipt: "receipt",
  image: "image", file: "file-text", spark: "sparkles", left: "chevron-left", right: "chevron-right",
  search: "search", play: "play", star: "star", fork: "git-fork", clock: "clock", calendar: "calendar",
  target: "target", gift: "gift", rocket: "rocket", party: "party-popper", verified: "badge-check",
  external: "external-link", globe: "globe", pin: "map-pin", building: "building-2", piggy: "piggy-bank",
  coins: "hand-coins", trend: "trending-up", zap: "zap", layers: "layers", activity: "activity",
  type: "type", palette: "palette", eye: "eye", radio: "radio", video: "clapperboard", git: "git-commit-horizontal",
  milestone: "milestone", wins: "medal", spending: "chart-pie", donors: "hand-heart", sources: "satellite-dish",
};
// slug used in the app → Simple Icons slug
const BRANDS = {
  github: "github", githubsponsors: "githubsponsors", instagram: "instagram", youtube: "youtube", discord: "discord",
  patreon: "patreon", kofi: "kofi", buymeacoffee: "buymeacoffee", opencollective: "opencollective",
  liberapay: "liberapay", paypal: "paypal", bitcoin: "bitcoin", ethereum: "ethereum", x: "x", tiktok: "tiktok",
  threads: "threads", bluesky: "bluesky", twitch: "twitch", reddit: "reddit", facebook: "facebook",
  mastodon: "mastodon", npm: "npm", gmail: "gmail",
};

const inner = (svg) => svg
  .replace(/<!--[\s\S]*?-->/g, "")
  .replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "")
  .replace(/<title>[\s\S]*?<\/title>/, "")
  .replace(/\s*\n\s*/g, "").trim();

async function get(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r.text();
}

const out = { ui: {}, brand: {} };
const missing = [];
await Promise.all([
  ...Object.entries(UI).map(async ([k, name]) => {
    try { out.ui[k] = inner(await get(`https://cdn.jsdelivr.net/npm/lucide-static@${LUCIDE}/icons/${name}.svg`)); }
    catch { missing.push(`lucide:${name}`); }
  }),
  ...Object.entries(BRANDS).map(async ([k, slug]) => {
    try { out.brand[k] = inner(await get(`https://cdn.jsdelivr.net/npm/simple-icons@${SIMPLE}/icons/${slug}.svg`)); }
    catch { missing.push(`simple-icons:${slug}`); }
  }),
]);
const sort = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
const js = `/* Generated by scripts/build-icons.mjs — do not edit by hand.
 * UI icons: Lucide ${LUCIDE} (ISC, https://lucide.dev)
 * Brand icons: Simple Icons ${SIMPLE} (CC0, https://simpleicons.org); trademarks belong to their owners. */
window.LEDGER_ICONS = ${JSON.stringify({ ui: sort(out.ui), brand: sort(out.brand) }, null, 0).replace(/","/g, '",\n"')};
`;
await writeFile(new URL("../js/icons.js", import.meta.url), js);
console.log(`js/icons.js: ${Object.keys(out.ui).length} UI + ${Object.keys(out.brand).length} brand icons${missing.length ? ` · missing: ${missing.join(", ")}` : ""}`);
